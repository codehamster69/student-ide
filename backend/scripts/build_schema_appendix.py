"""Generate the thesis's event-schema table (thesis/latex/tables/event-schema.tex) from schema.py.

The thesis appendix on the event schema must say exactly what the editor records, so the
per-type field table is generated from the pydantic payload models rather than typed by hand.
tests/test_schema_appendix.py fails when the committed table is out of date.

    cd backend && python scripts/build_schema_appendix.py            # rewrite the table
    cd backend && python scripts/build_schema_appendix.py --check    # exit 1 if stale
"""

from __future__ import annotations

import sys
import typing
from pathlib import Path

from pydantic_core import PydanticUndefined

from studentide import schema

OUT = Path(__file__).resolve().parents[2] / "thesis" / "latex" / "tables" / "event-schema.tex"

# Schema version in which each event type first appeared (see schema.py's docstring).
SINCE = {"term_cmd": 2, "term_output": 2, "term_paste": 2, "pkg_install": 2, "net_conn": 2,
         "fs_change": 3, "port_open": 3}


def _tex(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("&", r"\&"), ("%", r"\%"),
                 ("#", r"\#"), ("{", r"\{"), ("}", r"\}"), ("$", r"\$")):
        if a != "\\":
            s = s.replace(a, b)
    return s


def _type(ann) -> str:
    origin = typing.get_origin(ann)
    args = typing.get_args(ann)
    if origin is typing.Literal:
        return " | ".join(f'"{a}"' for a in args)
    if origin in (typing.Union, getattr(__import__("types"), "UnionType", None)):
        parts = [_type(a) for a in args if a is not type(None)]
        return " | ".join(parts) + (" | null" if type(None) in args else "")
    if origin in (list, tuple):
        return f"{origin.__name__}[{', '.join(_type(a) for a in args)}]"
    return getattr(ann, "__name__", str(ann))


def _default(field) -> str:
    if field.is_required():
        return "required"
    d = field.default
    if d is PydanticUndefined:
        return ""
    if d is None:
        return "null"
    if isinstance(d, bool):
        return "false" if not d else "true"
    if isinstance(d, str):
        return f'"{d}"'
    return str(d)


def _summary(model) -> str:
    doc = (model.__doc__ or "").strip().split("\n\n")[0]
    return " ".join(doc.split())


def build() -> str:
    lines = [
        "% Generated by backend/scripts/build_schema_appendix.py from backend/studentide/schema.py.",
        "% Do not edit by hand; rerun the script after a schema change.",
        r"\begingroup\small",
        r"\begin{longtable}{@{}p{0.2\linewidth}p{0.5\linewidth}p{0.22\linewidth}@{}}",
        r"\caption{Event payloads by type (schema version %d). Every event also carries"
        r" \texttt{seq}, \texttt{t} and \texttt{type}.}\label{tab:event-schema}\\" % schema.SCHEMA_VERSION,
        r"\toprule Field & Type & Default \\ \midrule \endfirsthead",
        r"\toprule Field & Type & Default \\ \midrule \endhead",
        r"\bottomrule \endfoot",
    ]
    seen: set[type] = set()
    for name, model in schema.PAYLOADS.items():
        names = [n for n, m in schema.PAYLOADS.items() if m is model]
        if model in seen:
            continue
        seen.add(model)
        since = SINCE.get(name, 1)
        head = ", ".join(rf"\texttt{{{_tex(n)}}}" for n in names)
        tag = f" (since v{since})" if since > 1 else ""
        lines.append(rf"\multicolumn{{3}}{{@{{}}p{{0.95\linewidth}}}}{{{head}{tag}: {_tex(_summary(model))}}} \\*")
        for fname, field in model.model_fields.items():
            lines.append(rf"\quad\texttt{{{_tex(fname)}}} & \texttt{{{_tex(_type(field.annotation))}}} & "
                         rf"\texttt{{{_tex(_default(field))}}} \\")
        lines.append(r"\midrule")
    lines[-1] = ""
    lines += [r"\end{longtable}", r"\endgroup", ""]
    return "\n".join(lines)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("up to date" if ok else f"stale: rerun {Path(__file__).name}")
        return 0 if ok else 1
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
