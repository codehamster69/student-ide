def rq3_drift_table(rq: dict, split: str = "all") -> str:
    d = rq["rq3_drift"][split]
    rows = [" & ".join([b["bin"], f"{b['sessions']} ({b['students']})", num(b["hours"], 1), num(b["identity"], 2, b["identity_ci"]),
                        num(b["pairs"], 2, b["pairs_ci"]), num(b["process"], 2, b["process_ci"]), num(b["fa_per_h"], 2, b["fa_ci"])])
            for b in d["bins"] if b["sessions"]]
    rho = ", ".join(f"{CH[c]} {num(d['spearman'][c], 2, d['spearman_ci'][c])}" for c in ("identity", "pairs", "process"))
    cap = (f"RQ3 drift: median per-session score of each channel by time since the end of the student's baseline"
           f" (all scored real sessions; 0 = like the baseline, larger = less like it), and alarms per active hour at the frozen"
           f" thresholds. Spearman correlation of score with days: {rho}.")
    return table(cap, "tab:cls-rq3-drift", "@{}lrrrrrr@{}",
                 "Since baseline & Sessions (students) & Hours & Rhythm & Key pairs & Way of working & Alarms / h", rows)


def rq3_profile_table(rq: dict) -> str:
    P = rq["rq3_profiles"]
    rows = []
    for lab, e in [(f"Same student, same device class, {k}", v) for k, v in P["gap"].items() if v["pairs"]] + \
                  [("Same student, same device class, all", P["pairs"]["same"]),
                   ("Same student, other device class", P["pairs"]["cross"]),
                   ("Other students, same question and device class", P["pairs"]["between"])]:
        if lab.endswith(", all") or lab.startswith("Other"):
            rows.append("\\midrule")
        rows.append(" & ".join([lab, f"{e['pairs']} ({e['students']})", num(e["rhythm"], 2, e["rhythm_ci"]), num(e["process"], 2, e["process_ci"])]))
    sp = P["spearman_days"]
    cap = (f"RQ3: how far apart two session profiles are (median of each feature over a session's active windows; mean absolute"
           f" difference in population MAD units, capped at 6), for {P['sessions']} sessions of {P['students']} students with at"
           f" least two minutes of typing on a lab-PC-like or personal-like machine. Medians over students, 95\\% intervals"
           f" resampling students. Spearman correlation of distance with days apart, same device class: rhythm"
           f" {num(sp['rhythm']['rho'], 2, sp['rhythm']['ci'])}, way of working {num(sp['process']['rho'], 2, sp['process']['ci'])}.")
    return table(cap, "tab:cls-rq3-profiles", "@{}lrrr@{}", "Pair of sessions & Pairs (students) & Rhythm distance & Way-of-working distance", rows)


def plot_drift(path: Path, rq: dict):
    plt = _plt()
    bins = [b for b in rq["rq3_drift"]["all"]["bins"] if b["sessions"]]
    fig, ax = plt.subplots(figsize=(4.6, 2.6))
    x = range(len(bins))
    for i, c in enumerate(("identity", "pairs", "process")):
        y = [b[c] for b in bins]
        lo = [b[c] - b[f"{c}_ci"][0] for b in bins]
        hi = [b[f"{c}_ci"][1] - b[c] for b in bins]
        ax.errorbar([v + (i - 1) * 0.12 for v in x], y, yerr=[lo, hi], color=C[i], marker=MARKERS[i], markersize=4,
                    linestyle=STYLES[i], linewidth=1.2, capsize=2, label=CH[c])
    ax.axhline(0, color=INK2, linewidth=0.7, linestyle=":")
    ax.set_xticks(list(x), [b["bin"] for b in bins])
    ax.set_xlabel("time since the end of the baseline")
    ax.set_ylabel("median session score")
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


