GEN = "% Generated by studentide.harness.classroom_report. Do not edit by hand."
METHOD = {"thesis": "Thesis detector (all channels)", "thesis_identity": "\\quad identity channels only",
          "thesis_process": "\\quad process channel only", "deployed": "Thesis detector, deployed thresholds",
          "sm": "Scaled Manhattan", "typenet": "TypeNet-style LSTM", "nosi": "Nosi-style L-scale"}
ATTR = {"device": "Device class", "os": "Operating system", "lang": "Language", "ctx": "Context", "speed": "Typing speed"}
CH = {"identity": "rhythm", "pairs": "key pairs", "process": "way of working"}


def nan(v) -> bool:
    return v is None or (isinstance(v, float) and math.isnan(v))


def pct(v, c=None) -> str:
    if nan(v):
        return "--"
    s = f"{100 * v:.0f}\\%"
    return s + (f" {{\\scriptsize[{100 * c[0]:.0f}, {100 * c[1]:.0f}]}}" if c and not nan(c[0]) else "")


def num(v, nd=2, c=None) -> str:
    if nan(v):
        return "--"
    s = f"{v:.{nd}f}"
    return s + (f" {{\\scriptsize[{c[0]:.{nd}f}, {c[1]:.{nd}f}]}}" if c and not nan(c[0]) else "")


def mins(v, c=None) -> str:
    if nan(v):
        return "--"
    s = f"{v / 60:.1f}"
    return s + (f" {{\\scriptsize[{c[0] / 60:.1f}, {c[1] / 60:.1f}]}}" if c and not nan(c[0]) else "")


def table(caption, label, cols, header, rows, note=None) -> str:
    L = [GEN, "\\begin{table}[ht]", "  \\centering\\small", f"  \\caption{{{caption}}}", f"  \\label{{{label}}}",
         f"  \\resizebox{{\\linewidth}}{{!}}{{\\begin{{tabular}}{{{cols}}}", "    \\toprule", f"    {header} \\\\", "    \\midrule"]
    L += [f"    {r} \\\\" if not r.startswith("\\") else f"    {r}" for r in rows]
    L += ["    \\bottomrule", "  \\end{tabular}}"]
    if note:
        L.append(f"  \\par\\smallskip\\parbox{{\\linewidth}}{{\\footnotesize {note}}}")
    L += ["\\end{table}", ""]
    return "\n".join(L)


def _plt():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    _style(plt)
    return plt


