def rq1_methods(t: dict, fz: dict) -> str:
    R = t["results"]
    rows = []
    for key in ("thesis", "thesis_identity", "thesis_process", "deployed", "sm", "typenet", "nosi"):
        m = R[key]["metrics"]
        h, a, b = m["honest"], m.get("takeover", {}), m.get("takeover_random", {})
        rows.append(" & ".join([METHOD[key], num(h["fa_per_h"], 2, h["fa_per_h_ci"]), pct(h["flagged"]),
                                pct(a.get("detected"), a.get("detected_ci")), mins(a.get("delay_median_s"), a.get("delay_ci")),
                                pct(b.get("detected"), b.get("detected_ci"))]))
        if key in ("thesis_process", "deployed"):
            rows.append("\\midrule")
    m = R["thesis"]["metrics"]
    cap = (f"RQ1 on the held-out classroom split ({t['evaluate']['test_students']} test students plus the sessions from 24 November"
           f" of {t['evaluate']['dev_students_with_later_sessions']} dev students; {m['honest']['n']} real sessions,"
           f" {m['honest']['hours']:.1f} active hours; {m.get('takeover', {}).get('n', 0)} same-device and"
           f" {m.get('takeover_random', {}).get('n', 0)} cross-device splices), each method at thresholds frozen on the dev split"
           f" for {fz['target_fa_per_h']:g} false alarms per hour ({fz['calibration_source']} calibration). Scored once"
           f" (\\texttt{{test-ledger.jsonl}}). Brackets: 95\\% intervals, resampling students.")
    return table(cap, "tab:cls-rq1", "@{}lrrrrr@{}",
                 "Method & False alarms / h & Sessions flagged & Same-device caught & Delay (min) & Cross-device caught",
                 rows, "The deployed row keeps the thresholds calibrated on simulated typists, which the live site still uses.")


def rq1_dev_methods(d: dict, fz: dict) -> str:
    rows = []
    entries = [("thesis", d["at_target"]), ("thesis_identity", d["identity_at_target"]), ("deployed", d["deployed"])]
    entries += [(k, d["methods"][k]["metrics"]) for k in ("sm", "typenet", "nosi") if k in d.get("methods", {})]
    for key, m in entries:
        h, a = m["honest"], m.get("takeover", {})
        rows.append(" & ".join([METHOD[key], num(h["fa_per_h"], 2, h["fa_per_h_ci"]), pct(h["flagged"], h["flagged_ci"]),
                                pct(a.get("detected"), a.get("detected_ci")), mins(a.get("delay_median_s"), a.get("delay_ci")),
                                pct(m.get("precision_100"), m.get("precision_100_ci")), pct(m.get("precision_500"), m.get("precision_500_ci"))]))
        if key == "deployed":
            rows.append("\\midrule")
    m = d["at_target"]
    cap = (f"RQ1 and RQ4 on the dev split, 5-fold cross-fitted: each fold's thresholds come from the other folds' students"
           f" ({fz['calibration_source']} calibration, {fz['target_fa_per_h']:g} false alarms per hour), so every number is out of"
           f" sample for the thresholds. {m['honest']['n']} real sessions of {m['honest']['students']} students,"
           f" {m['honest']['hours']:.1f} active hours, {m.get('takeover', {}).get('n', 0)} same-device splices."
           f" Precision assumes 1 in 100 or 1 in 500 sessions contain a takeover.")
    return table(cap, "tab:cls-dev-methods", "@{}lrrrrrr@{}",
                 "Method & False alarms / h & Sessions flagged & Same-device caught & Delay (min) & Precision 1/100 & 1/500", rows)


def rq1_dev(d: dict, fz: dict) -> str:
    rows = []
    for lab, m in (("Frozen thresholds, all channels", d["at_target"]), ("\\quad identity channels only", d["identity_at_target"]),
                   ("Deployed thresholds (simulated calibration)", d["deployed"])):
        h, a = m["honest"], m.get("takeover", {})
        rows.append(" & ".join([lab, num(h["fa_per_h"], 2, h["fa_per_h_ci"]), pct(a.get("detected"), a.get("detected_ci")),
                                mins(a.get("delay_median_s"), a.get("delay_ci"))]))
    rows.append("\\midrule")
    for src in ("holdout", "self", "pooled"):
        ach = {r["target"]: r["achieved"] for r in d["calibration_check"] if r["source"] == src}
        rows.append(f"Calibration on {src}: achieved at targets " + ", ".join(f"{t:g}" for t in sorted(ach)) +
                    " & \\multicolumn{3}{l}{" + ", ".join(num(ach[t], 2) for t in sorted(ach)) + "}")
    cap = (f"Freezing the thresholds on the dev split (5-fold cross-fitted; {d['at_target']['honest']['n']} real sessions,"
           f" {d['at_target']['honest']['hours']:.1f} active hours, {d['at_target'].get('takeover', {}).get('n', 0)} same-device splices)."
           f" Detector settings are the live ones; only $h$ and the calibration source were chosen here"
           f" (lowest mean $|\\log(\\text{{achieved}}/\\text{{target}})|$: {fz['calibration_source']}).")
    return table(cap, "tab:cls-dev", "@{}lrrr@{}", "Dev split & False alarms / h & Same-device caught & Delay (min)", rows)


def plot_curves(path: Path, t: dict, d: dict):
    plt = _plt()
    fig, axs = plt.subplots(1, 2, figsize=(6.8, 2.7), sharey=True)
    for ax, (key, title) in zip(axs, (("takeover", "same-device splices"), ("takeover_random", "cross-device splices"))):
        for i, m in enumerate(("thesis", "sm", "typenet", "nosi")):
            rows = t["results"][m]["curve"]
            ax.plot([max(r["fa_per_h"], 0.02) for r in rows], [100 * r.get(key, math.nan) for r in rows], color=C[i],
                    linestyle=STYLES[i], marker=MARKERS[i], markersize=3, linewidth=1.3,
                    label=METHOD[m].replace("Thesis detector (all channels)", "Thesis detector"))
        ax.plot([max(r["fa_per_h"], 0.02) for r in d["curve"]], [100 * r.get(key, math.nan) for r in d["curve"]], color=INK2,
                linestyle=":", linewidth=1.0, label="Thesis detector, dev split")
        ax.set_xscale("log")
        ax.set_title(title, fontsize=9, color=INK)
        ax.set_xlabel("false alarms per active hour (real sessions)")
        ax.axvline(0.2, color=INK2, linewidth=0.7, linestyle=":")
        ax.set_ylim(0, 102)
    axs[0].set_ylabel("splices caught (%)")
    axs[0].legend(fontsize=6.5, loc="upper left")
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


