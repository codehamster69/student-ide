def table_methods(rows: list[dict], meta: str, target: float) -> str:
    L = _head(meta, f"RQ1 on the synthetic test students: the thesis detector against the baselines, each with its"
              f" alarm threshold calibrated on dev students for $\\le {target:g}$ false alarms per honest hour"
              f" (alarm rule, $k$ and window chosen on dev, \\cref{{tab:harness-tuning}}). Detected = alarm after the switch; delay = median for matched"
              f" takeovers; Win.\\ AUC = one window, honest vs.\\ typed by another person.",
              "tab:harness-methods", "@{}lcccccccrr@{}",
              "Method & Win.\\ AUC & Proxy & Takeover & Take.\\ (rand.) & Copying & Paste & Delay (s) & FA/h & Flagged")
    for r in rows:
        L.append(f"    {esc(r['method'])} & {f(r['window_auc'], 2)} & " + " & ".join(f(r[v], pct=True) for v in CHEAT) +
                 f" & {f(r['takeover_delay'])} & {f(r['fa_per_h'], 2)} & {f(r['flagged'], pct=True)} \\\\")
    return "\n".join(L + _tail())


def table_conditions(summ: dict, cis: dict, meta: str, h: dict, k: dict) -> str:
    hs = "/".join(f"{v:g}" for v in h.values())
    ks = "/".join(f"{v:g}" for v in k.values())
    hon = summ["honest"]
    L = _head(meta, f"Thesis detector by condition on the synthetic test students ($k={ks}$, $h={hs}$ for"
              f" identity/process, 95\\% student-bootstrap intervals). Honest sessions: {hon['fa_per_h']:.2f}"
              f"{ci(*cis['fa'], nd=2)} false alarms per hour, {100 * hon['flagged']:.0f}\\%{ci(*cis['flagged'], pct=True)}"
              f" of honest sessions with at least one alarm.",
              "tab:harness-conditions", "@{}lrlrrrrc@{}",
              "Condition & $n$ & Detected & Delay med.\\ (s) & Delay p90 (s) & Switch err.\\ (s) & Early alarms & First: id/proc")
    for v in CHEAT:
        c = summ[v]
        fc = c["first_channel"]
        L.append(f"    {VARIANT_LABELS[v]} & {c['n']} & {f(c['detected'], pct=True)}{ci(*cis[v], pct=True)} & "
                 f"{f(c['delay_median_s'])}{ci(*cis[v + '_delay'])} & {f(c['delay_p90_s'])} & {f(c['switch_err_median_s'])} & "
                 f"{c['early_alarms']} & {fc.get('identity', 0)}/{fc.get('process', 0)} \\\\")
    return "\n".join(L + _tail())


def table_tuning(rows: list[dict], meta: str) -> str:
    L = _head(meta, "Hyperparameters of each method chosen on the dev students (5-fold cross-fitting, $\\le 0.2$"
              " false alarms per hour). Objective: mean detection over the five non-honest conditions. Bold = chosen.",
              "tab:harness-tuning", "@{}llrrccr@{}", "Method & Rule & $k$ & $W$ (s) & Mean detected & Takeover & FA/h")
    for r in rows:
        b = (lambda s: f"\\textbf{{{s}}}") if r.get("chosen") else (lambda s: s)
        L.append(f"    {b(esc(r['method']))} & {r['rule']} & {r['k']:g} & {r['window_s']:g} & {b(f(r['mean_detected'], pct=True))} & "
                 f"{f(r['takeover'], pct=True)} & {f(r['fa_per_h'], 2)} \\\\")
    return "\n".join(L + _tail())


