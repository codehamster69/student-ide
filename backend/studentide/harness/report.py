CHEAT = ["proxy", "takeover", "takeover_random", "copying", "paste"]
SHORT = {"proxy": "Proxy", "takeover": "Takeover", "takeover_random": "Takeover (rand.)", "copying": "Copying", "paste": "Paste"}
MARKERS = ["o", "s", "^", "D", "v"]
STYLES = ["-", "--", "-.", ":", "-"]


def f(v, nd=0, pct=False):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "--"
    return f"{100 * v:.0f}\\%" if pct else f"{v:.{nd}f}"


def ci(lo, hi, pct=False, nd=0):
    if lo is None or (isinstance(lo, float) and math.isnan(lo)):
        return ""
    if pct:
        return f" {{\\scriptsize[{100 * lo:.0f}, {100 * hi:.0f}]}}"
    return f" {{\\scriptsize[{lo:.{nd}f}, {hi:.{nd}f}]}}"


def _head(meta: str, caption: str, label: str, cols: str, header: str) -> list[str]:
    return [f"% Generated by studentide.harness ({meta}). Do not edit by hand.",
            "\\begin{table}[ht]", "  \\centering\\small", f"  \\caption{{{caption}}}", f"  \\label{{{label}}}",
            f"  \\resizebox{{\\linewidth}}{{!}}{{\\begin{{tabular}}{{{cols}}}", "    \\toprule", f"    {header} \\\\", "    \\midrule"]


def _tail() -> list[str]:
    return ["    \\bottomrule", "  \\end{tabular}}", "\\end{table}", ""]


def esc(s: str) -> str:
    return s.replace("_", "\\_").replace("%", "\\%")


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


