SEARCH_TAGS = ("Depth-First Search", "Breadth-First Search")  # graphs, unless the problem is about a tree

# Shown before the dataset's starter code: what LeetCode's Python environment
# already provides, so solutions written the LeetCode way run here too.
PRELUDE = """\
# Provided, as on LeetCode: common imports{nodes}.
from typing import *
from collections import *
from functools import *
from itertools import *
from heapq import *
from bisect import *
import math
inf = float("inf")
"""
LIST_NODE = """
class ListNode:
    def __init__(self, val=0, next=None):
        self.val = val
        self.next = next
"""
TREE_NODE = """
class TreeNode:
    def __init__(self, val=0, left=None, right=None):
        self.val = val
        self.left = left
        self.right = right
"""

HARNESS = '''\
# Student IDE test driver: builds the test's arguments, calls Solution().{fn}
# and prints what it returns as JSON (linked lists and trees as lists).
import json as _json, sys as _sys
from collections import deque as _deque
try:
    ListNode
except NameError:
    class ListNode:
        def __init__(self, val=0, next=None):
            self.val, self.next = val, next
try:
    TreeNode
except NameError:
    class TreeNode:
        def __init__(self, val=0, left=None, right=None):
            self.val, self.left, self.right = val, left, right


def _list_node(values):
    head = None
    for v in reversed(values):
        head = ListNode(v, head)
    return head


def _tree_node(values):
    if not values:
        return None
    root = TreeNode(values[0])
    queue, i = _deque([root]), 1
    while queue and i < len(values):
        node = queue.popleft()
        if values[i] is not None:
            node.left = TreeNode(values[i])
            queue.append(node.left)
        i += 1
        if i < len(values) and values[i] is not None:
            node.right = TreeNode(values[i])
            queue.append(node.right)
        i += 1
    return root


def _show(x, any_order=False):
    if isinstance(x, ListNode):
        out = []
        while x is not None and len(out) < 100000:
            out.append(_show(x.val))
            x = x.next
        return out
    if isinstance(x, TreeNode):
        out, queue = [], _deque([x])
        while queue:
            node = queue.popleft()
            out.append(None if node is None else _show(node.val))
            if node is not None:
                queue.extend((node.left, node.right))
        while out and out[-1] is None:
            out.pop()
        return out
    if isinstance(x, (list, tuple)):
        out = [_show(v, any_order) for v in x]
        return sorted(out, key=_json.dumps) if any_order else out
    if isinstance(x, (set, frozenset)):
        return sorted((_show(v, any_order) for v in x), key=_json.dumps)
    if isinstance(x, dict):
        return {{str(k): _show(v, any_order) for k, v in x.items()}}
    return x


_args = eval("dict(" + _sys.stdin.read() + ")", {{"__builtins__": {{"dict": dict}}, "list_node": _list_node,
                                                   "tree_node": _tree_node, "inf": float("inf")}})
print(_json.dumps(_show(Solution().{fn}(**_args), {any_order})))
'''


def harness(fn: str, any_order: bool) -> str:
    return HARNESS.format(fn=fn, any_order=any_order)


def starter(row: dict) -> str:
    nodes = [n for n, src in (("ListNode", LIST_NODE), ("TreeNode", TREE_NODE)) if n in row["starter_code"]]
    head = PRELUDE.format(nodes=" and the " + " and ".join(f"{n} class" for n in nodes) if nodes else "")
    head += "".join(src for n, src in (("ListNode", LIST_NODE), ("TreeNode", TREE_NODE)) if n in nodes)
    # The dataset's starter keeps LeetCode's commented-out node definitions; the real ones are above.
    body = "\n".join(line for line in row["starter_code"].rstrip().splitlines() if not line.lstrip().startswith("#"))
    indent = len(body.splitlines()[-1]) - len(body.splitlines()[-1].lstrip()) + 4
    return f"{head}\n\n{body}\n{' ' * indent}pass\n"


@lru_cache(maxsize=1)
def _load() -> dict[str, dict]:
    if not DATA.exists():
        raise ProviderError("the LeetCode question set is missing from this install", 503)
    with gzip.open(DATA, "rt", encoding="utf-8") as f:
        return {r["ref"]: r for r in map(json.loads, f)}


def topics(row: dict) -> list[str]:
    tags = set(row["tags"])
    out = {t for tag in tags for t in TAG_TOPICS.get(tag, ())}
    if tags & set(SEARCH_TAGS) and not tags & {"Tree", "Binary Tree", "Binary Search Tree"}:
        out.add("graphs")
    return sorted(out)


def live_prompt(row: dict) -> dict:
    """Where the browser fetches the problem text from (and how to check it got the right row)."""
    return {"url": f"{ROWS_URL}?dataset={DATASET.replace('/', '%2F')}&config=default&split={row['split']}"
                   f"&offset={row['offset']}&length=1",
            "field": "problem_description", "match": {"task_id": row["ref"]},
            "fallback": f"/api/live-prompt/leetcode/{row['ref']}",
            "credit": "Problem text by LeetCode, loaded live from LeetCodeDataset on Hugging Face"}


class LeetCode(Provider):
    id = "leetcode"
    name = "LeetCode"
    status = "bundled"
    license = "Apache 2.0 (tests and tags); problem text LeetCode's"
    about = ("2,800+ LeetCode problems by topic and difficulty, each with tests, from LeetCodeDataset. LeetCode's "
             "problem text is not stored: it loads live when the question is shown, or you write your own. Python labs only.")
    terms_url = "https://huggingface.co/datasets/newfacade/LeetCodeDataset"
    hosts = ("leetcode.com", "leetcode.cn")

    def __init__(self, get: Fetcher = http_get, ttl: float = CACHE_TTL_S):
        self.get, self.ttl = get, ttl
        self._texts: dict[str, tuple[float, str]] = {}  # in memory only: the text is never written anywhere

    def live_text(self, ref: str) -> str:
        """LeetCode's text for one problem, fetched from the dataset viewer when a
        browser couldn't reach it itself (e.g. a campus network that blocks it)."""
        hit = self._texts.get(ref)
        if hit and time.time() - hit[0] < self.ttl:
            return hit[1]
        r = _load().get(ref)
        if r is None:
            raise ProviderError(f"no LeetCode problem '{ref}' in the question set", 404)
        lp = live_prompt(r)
        body = self.get(lp["url"])
        try:
            row = json.loads(body or b"{}")["rows"][0]["row"]
        except (ValueError, KeyError, IndexError, TypeError):
            row = {}
        if row.get("task_id") != ref or not row.get(lp["field"]):
            raise ProviderError("the problem text is not available right now")
        if len(self._texts) > 500:
            self._texts.clear()
        self._texts[ref] = (time.time(), row[lp["field"]].strip())
        return self._texts[ref][1]

    def _rows(self, language: str) -> list[dict]:
        if language != "python":
            raise ProviderError("LeetCode questions are Python only (the tests call a Solution method); "
                                "switch the lab to Python to use them, or link a problem instead", 400)
        return list(_load().values())

    def _row(self, language: str, ref: str) -> dict:
        self._rows(language)
        r = _load().get(ref)
        if r is None:
            raise ProviderError(f"no LeetCode problem '{ref}' in the question set", 404)
        return r

    def categories(self, language: str) -> list[Category]:
        rows = self._rows(language)
        return topic_categories([topics(r) for r in rows],
                                [(k, label, sum(r["difficulty"] == k for r in rows)) for k, label in LEVELS])

    def search(self, language: str, category: str | None = None, query: str = "") -> list[Summary]:
        q = query.strip().lower()
        out = []
        for r in self._rows(language):
            if category and category.startswith("topic:") and category[6:] not in topics(r):
                continue
            if category and category.startswith("level:") and category[6:] != r["difficulty"]:
                continue
            if q and q not in r["title"].lower() and q not in r["ref"] and q != str(r["id"]):
                continue
            out.append(Summary(r["ref"], f"{r['id']}. {r['title']}", r["difficulty"], r["tags"]))
        order = [k for k, _ in LEVELS]
        return sorted(out, key=lambda s: (order.index(s.difficulty), int(s.title.split(".")[0])))[:400]

    def fetch(self, language: str, ref: str) -> Imported:
        r = self._row(language, ref)
        tests = [{"name": f"Example {i + 1}" if i < 2 else f"Test {i + 1}", "stdin": t["stdin"], "expected": t["expected"],
                  "hidden": i >= 2, "compare": "json"} for i, t in enumerate(r["tests"])]
        notes = ["The problem text isn't stored: students see it loaded live from LeetCodeDataset (or your own "
                 "words, if you write a prompt). Tests call Solution()." + r["fn"] + " and compare what it returns."]
        if r["any_order"]:
            notes.append("Answers may come in any order, so lists are compared after sorting.")
        return Imported(
            title=f"{r['id']}. {r['title']}", prompt="", starter_code=starter(r), tests=tests,
            harness=harness(r["fn"], r["any_order"]),
            source={"provider": self.id, "ref": ref, "url": f"https://leetcode.com/problems/{ref}/",
                    "license": self.license, "attribution": ATTRIBUTION, "tags": r["tags"], "level": r["difficulty"],
                    "live_prompt": live_prompt(r), "fetched_at": time.time()},
            notes=notes,
        )
