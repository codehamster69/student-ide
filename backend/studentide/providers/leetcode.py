"""LeetCode problems from LeetCodeDataset, with tests and topics but without
LeetCode's problem text.

LeetCodeDataset (Xia et al., 2025, arXiv:2504.14655; Hugging Face
newfacade/LeetCodeDataset, Apache 2.0) collects 2,869 LeetCode problems with
their topic tags, difficulty, starter code and about 100 test asserts each,
generated by the dataset's authors and checked against reference solutions.
The tests, tags and starter code are the authors' work and are bundled here
(data/leetcode.jsonl.gz, built by scripts/build_leetcode.py).

The problem descriptions in the dataset are copied from LeetCode, which
claims copyright in them, so they are never stored by this app: an imported
question keeps an empty prompt and a pointer to the dataset row, and the
student's (or teacher's) browser loads the text live from the Hugging Face
dataset viewer when the question is shown. A teacher may write their own
prompt instead, which then replaces the live text. The original problem is
linked on leetcode.com either way.

In Python the tests call a method on `class Solution`, as on LeetCode: the
harness below builds the arguments (including linked lists and binary
trees), calls the method and prints its return value as JSON. C, C++, Java
and JavaScript labs get the same tests with one JSON argument per stdin line
and a starter and harness generated from the method's type hints
(polyglot.py); the expected outputs are the same.
"""

